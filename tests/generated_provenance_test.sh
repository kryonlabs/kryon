#!/usr/bin/env sh
set -eu

root="${1:-.}"
cd "$root"

status=0

require_first_line() {
    file=$1
    pattern=$2
    if ! head -n 1 "$file" | rg -q "$pattern"; then
        echo "missing generated provenance in first line of $file" >&2
        status=1
    fi
}

require_contains() {
    file=$1
    pattern=$2
    if ! rg -q "$pattern" "$file"; then
        echo "missing generated provenance marker in $file" >&2
        status=1
    fi
}

require_first_line include/ui_icon_types.h 'Generated by scripts/embed-icons\.sh'
require_first_line src/ui/ui_icon_names.c 'Generated by scripts/embed-icons\.sh'
require_first_line src/ui/ui_icon_assets.c 'Generated by scripts/embed-icons\.sh'
require_first_line docs/PUBLIC_API_SNAPSHOT.txt 'Generated by scripts/public-api-snapshot\.py'
require_contains docs/FEATURE_MATRIX.html 'Generated by scripts/feature-matrix-html\.py'
require_contains docs/site/conformance-matrix.json '"source": "scripts/conformance-matrix.py"'

if [ "$status" -eq 0 ]; then
    echo "generated provenance ok"
fi

exit "$status"
