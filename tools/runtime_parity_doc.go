package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/ast"
	"go/parser"
	"go/printer"
	"go/token"
	"os"
	"sort"
	"strings"
)

type methodSet map[string]string

func main() {
	write := flag.Bool("write", false, "write docs/RUNTIME_PARITY.md")
	flag.Parse()

	cgoBridge, err := runtimeMethods("go/kryui/runtime.go")
	check(err)
	native, err := runtimeMethods("go/kryon/runtime.go")
	check(err)
	checkForbidden("go/kryon/runtime.go")

	doc, ok := render(cgoBridge, native)
	if *write {
		check(os.WriteFile("docs/RUNTIME_PARITY.md", []byte(doc), 0644))
	}
	if !ok {
		fmt.Fprint(os.Stderr, doc)
		os.Exit(1)
	}
	if !*write {
		got, err := os.ReadFile("docs/RUNTIME_PARITY.md")
		check(err)
		if string(got) != doc {
			fmt.Fprintln(os.Stderr, "docs/RUNTIME_PARITY.md is stale; run tests/runtime_parity_test.sh")
			os.Exit(1)
		}
	}
}

func runtimeMethods(path string) (methodSet, error) {
	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, path, nil, parser.ParseComments)
	if err != nil {
		return nil, err
	}
	out := methodSet{}
	for _, decl := range file.Decls {
		gd, ok := decl.(*ast.GenDecl)
		if !ok || gd.Tok != token.TYPE {
			continue
		}
		for _, spec := range gd.Specs {
			ts, ok := spec.(*ast.TypeSpec)
			if !ok || ts.Name.Name != "Runtime" {
				continue
			}
			iface, ok := ts.Type.(*ast.InterfaceType)
			if !ok {
				return nil, fmt.Errorf("%s: Runtime is not an interface", path)
			}
			for _, field := range iface.Methods.List {
				if len(field.Names) == 0 {
					continue
				}
				sig, err := methodSignature(fset, field.Type)
				if err != nil {
					return nil, err
				}
				out[field.Names[0].Name] = compactSignature(sig)
			}
			return out, nil
		}
	}
	return nil, fmt.Errorf("%s: Runtime interface not found", path)
}

func methodSignature(fset *token.FileSet, expr ast.Expr) (string, error) {
	ft, ok := expr.(*ast.FuncType)
	if !ok {
		var buf bytes.Buffer
		if err := printer.Fprint(&buf, fset, expr); err != nil {
			return "", err
		}
		return buf.String(), nil
	}
	params, err := fieldList(fset, ft.Params)
	if err != nil {
		return "", err
	}
	if ft.Results == nil {
		return params, nil
	}
	results, err := fieldList(fset, ft.Results)
	if err != nil {
		return "", err
	}
	return params + " " + results, nil
}

func fieldList(fset *token.FileSet, fields *ast.FieldList) (string, error) {
	if fields == nil {
		return "()", nil
	}
	parts := make([]string, 0, len(fields.List))
	for _, field := range fields.List {
		var typ bytes.Buffer
		if err := printer.Fprint(&typ, fset, field.Type); err != nil {
			return "", err
		}
		if len(field.Names) == 0 {
			parts = append(parts, typ.String())
			continue
		}
		names := make([]string, 0, len(field.Names))
		for _, name := range field.Names {
			names = append(names, name.Name)
		}
		parts = append(parts, strings.Join(names, ", ")+" "+typ.String())
	}
	return "(" + strings.Join(parts, ", ") + ")", nil
}

func compactSignature(sig string) string {
	return strings.Join(strings.Fields(sig), " ")
}

func checkForbidden(path string) {
	data, err := os.ReadFile(path)
	check(err)
	text := string(data)
	for _, forbidden := range []string{`import "C"`, "DrawUI", "UIText", "TextInputControl", "UIRender", "BeginDrawing", "EndDrawing", "github.com/waozixyz/kryon/go/kryui"} {
		if strings.Contains(text, forbidden) {
			fmt.Fprintf(os.Stderr, "%s contains forbidden native-runtime token %q\n", path, forbidden)
			os.Exit(1)
		}
	}
}

func render(cgoBridge, native methodSet) (string, bool) {
	names := make([]string, 0, len(cgoBridge)+len(native))
	seen := map[string]bool{}
	for name := range cgoBridge {
		names = append(names, name)
		seen[name] = true
	}
	for name := range native {
		if !seen[name] {
			names = append(names, name)
		}
	}
	sort.Strings(names)

	var b strings.Builder
	ok := true
	b.WriteString("# Runtime Parity\n\n")
	b.WriteString("Generated by `tests/runtime_parity_test.sh`. Do not edit by hand.\n\n")
	b.WriteString("| Method | Native Go (`go/kryon`) | Cgo bridge (`go/kryui`) | Status |\n")
	b.WriteString("|---|---|---|---|\n")
	for _, name := range names {
		ng, nok := native[name]
		lg, lok := cgoBridge[name]
		status := "ok"
		switch {
		case !nok:
			status = "missing native"
			ok = false
		case !lok:
			status = "missing cgo bridge"
			ok = false
		case ng != lg:
			status = "signature mismatch"
			ok = false
		}
		b.WriteString(fmt.Sprintf("| `%s` | `%s` | `%s` | %s |\n",
			name, display(ng, nok), display(lg, lok), status))
	}
	b.WriteString("\n## Generated Runtime Semantics\n\n")
	b.WriteString("`tests/generated_runtime_parity_test.sh` transpiles the fixtures in `tests/parity/` through k2g and k2c, rejects legacy generated output, drives both generated runtimes through text editing, click-to-focus, focus traversal, selection replacement, secure clipboard copy, buttons, rows, columns, text areas, and long-running text input with per-character cursor movement and Tab traversal, asserts generated Go emits renderable native frame operations without leaking secure text, renders those operations into visible pure-Go images, then diffs the final state JSON.\n")
	b.WriteString("\n## Native Host Text Input\n\n")
	b.WriteString("`go/kryon` tests run the native `Host` through thousands of text-input frames with cursor navigation on every typed character, Tab traversal between fields, stable frame operation counts, and bounded focus/selection bookkeeping.\n")
	return b.String(), ok
}

func display(sig string, ok bool) string {
	if !ok {
		return "-"
	}
	return sig
}

func check(err error) {
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
