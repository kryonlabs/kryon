#!/usr/bin/env python3
"""Embed a style pack as a Ziran module, so an application can install it
without shipping the .kss file. Usage: generate-style-pack-module.py classic

A Ziran string literal holds at most 4095 characters, so the pack is stored as
chunks that the module joins into one static buffer on first use."""

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CHUNK = 1800


def main() -> None:
    name = sys.argv[1]
    source = (ROOT / "styles" / "kryon" / f"{name}.kss").read_text()
    if "KSSEND" in source or not source.endswith("\n"):
        raise SystemExit("pack must end in a newline and not contain KSSEND")
    chunks, current = [], ""
    for line in source.splitlines(keepends=True):
        if len(current) + len(line) > CHUNK and current:
            chunks.append(current)
            current = ""
        current += line
    chunks.append(current)
    if any(len(chunk.encode()) > 3000 for chunk in chunks):
        raise SystemExit("a line is too long to embed")
    size = len(source.encode())
    out = [
        f"// Generated from styles/kryon/{name}.kss by scripts/generate-style-pack-module.py.\n",
        "// Edit the .kss and regenerate; do not edit this file.\n",
        f"style_pack_{name}_bytes: [{size + 1}]u8;\n",
        f"style_pack_{name}_length: s32 = 0;\n\n",
    ]
    for index, chunk in enumerate(chunks):
        out.append(f"StylePack{name.capitalize()}Chunk{index} :: #string KSSEND\n{chunk}KSSEND;\n\n")
    out.append(f"StylePack{name.capitalize()}Append :: (chunk: string) {{\n")
    out.append("    index: s32 = 0\n    while index < cast(s32)chunk.count {\n")
    out.append(f"        style_pack_{name}_bytes[style_pack_{name}_length + index] = chunk[index]\n")
    out.append("        index += 1\n    }\n")
    out.append(f"    style_pack_{name}_length += cast(s32)chunk.count\n}}\n\n")
    out.append(f"// The {name} style pack's KSS source.\n#program_export\nStylePack{name.capitalize()} :: () -> string {{\n")
    out.append(f"    if style_pack_{name}_length == 0 {{\n")
    for index in range(len(chunks)):
        out.append(f"        StylePack{name.capitalize()}Append(StylePack{name.capitalize()}Chunk{index})\n")
    out.append("    }\n")
    out.append(f"    return TextView(style_pack_{name}_bytes[0:style_pack_{name}_length])\n}}\n")
    module = ROOT / "src" / "kss" / f"style_pack_{name}.zi"
    module.write_text("".join(out))
    print(module, len(chunks), "chunks")


main()
