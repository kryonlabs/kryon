#!/bin/sh
set -eu

raylib_header=${1:-vendor/raylib/src/raylib.h}
public_header=${2:-include/kryon_compat.generated.h}
rename_header=${3:-build/generated/raylib_backend_rename.h}
wrapper_source=${4:-build/generated/kryon_raylib_wrappers.c}
null_backend_source=${5:-build/generated/kryon_null_backend.c}
backend_prefix=${KRYON_RAYLIB_BACKEND_PREFIX:-KryonRaylibBackend_}

if [ ! -f "$raylib_header" ]; then
    echo "raylib header not found: $raylib_header" >&2
    exit 1
fi

mkdir -p "$(dirname "$public_header")" "$(dirname "$rename_header")" "$(dirname "$wrapper_source")" "$(dirname "$null_backend_source")"

{
    echo "/* Generated by tools/generate-kryon-compat.sh; do not edit. */"
    cat <<'EOF'
/*
 * Kryon graphics/input API surface.
 *
 * This header defines kryon's public graphics, input, and asset API. It
 * currently tracks raylib's surface verbatim so that existing raylib-style
 * code (DrawRectangle, Font, BeginDrawing, ...) compiles unchanged, and so
 * the raylib backend (build/generated/kryon_raylib_wrappers.c) can implement
 * every symbol by forwarding to raylib.
 *
 * Kryon owns this surface. It is not "raylib that kryon happens to use":
 * other backends implement these same function and type names without raylib
 * (for example an HTML5 canvas backend). Selection is link-time, via the
 * KRYON_BACKEND make variable. The raylib version tracked below is the
 * baseline; kryon may evolve this surface independently over time.
 */
EOF
    cat <<'EOF'

#ifndef KRYON_KEY_PLATFORM_CALLBACKS_DEFINED
#define KRYON_KEY_PLATFORM_CALLBACKS_DEFINED

typedef void (*KeyInputPlatformCallback)(void);
typedef int (*KeyPlatformCallback)(int key);

int SetKeyboardInputEnabled(int enabled);
int KeyboardInputEnabled(void);
void SetKeyPlatformCallbacks(KeyInputPlatformCallback update,
                             KeyPlatformCallback key_pressed,
                             KeyPlatformCallback key_down);
void UpdateKeyPlatformState(void);

#endif

EOF
    cat "$raylib_header"
} > "$public_header"

{
    echo "/* Generated by tools/generate-kryon-compat.sh; do not edit. */"
    echo "#ifndef KRYON_RAYLIB_BACKEND_RENAME_H"
    echo "#define KRYON_RAYLIB_BACKEND_RENAME_H"
    echo
    awk '
        /^[[:space:]]*(RLAPI|RMAPI)[[:space:]]/ {
            line = $0
            sub(/\(.*/, "", line)
            n = split(line, parts, /[[:space:]\*]+/)
            if(n > 0 && parts[n] ~ /^[A-Za-z_][A-Za-z0-9_]*$/)
                print parts[n]
        }
    ' "$raylib_header" | sort -u | while IFS= read -r symbol; do
        [ -n "$symbol" ] || continue
        printf '#define %s %s%s\n' "$symbol" "$backend_prefix" "$symbol"
    done
    echo
    echo "#endif"
} > "$rename_header"

awk -v prefix="$backend_prefix" '
function trim(s) {
    sub(/^[[:space:]]+/, "", s)
    sub(/[[:space:]]+$/, "", s)
    return s
}

function function_name_from_prefix(prefix_text, parts, n) {
    n = split(prefix_text, parts, /[[:space:]\*]+/)
    return parts[n]
}

function return_type_from_prefix(prefix_text, name) {
    sub(/^[[:space:]]*(RLAPI|RMAPI)[[:space:]]+/, "", prefix_text)
    sub("[[:space:]]*" name "$", "", prefix_text)
    return trim(prefix_text)
}

function arg_name(arg, parts, n, name) {
    arg = trim(arg)
    sub(/=.*/, "", arg)
    gsub(/\[[^]]*\]/, "", arg)
    n = split(arg, parts, /[[:space:]\*]+/)
    name = parts[n]
    gsub(/[^A-Za-z0-9_]/, "", name)
    return name
}

function call_args(args, parts, count, i, name, out) {
    args = trim(args)
    if(args == "void" || args == "")
        return ""
    count = split(args, parts, /,[[:space:]]*/)
    out = ""
    for(i = 1; i <= count; i++) {
        if(parts[i] == "...")
            continue
        name = arg_name(parts[i])
        if(name == "")
            continue
        out = out (out == "" ? "" : ", ") name
    }
    return out
}

function emit_regular_wrapper(return_type, name, args, backend_args, returns_void) {
    print "extern " return_type " " prefix name "(" args ");"
    print return_type " " name "(" args ")"
    print "{"
    if(name == "IsKeyPressed") {
        print "    if(!g_kryon_keyboard_input_enabled)"
        print "        return false;"
        print "    if(g_kryon_key_pressed_callback != NULL && k_key_prefers_platform(key))"
        print "        return g_kryon_key_pressed_callback(key);"
        print "    if(" prefix name "(" backend_args "))"
        print "        return true;"
        print "    return g_kryon_key_pressed_callback != NULL &&"
        print "           g_kryon_key_pressed_callback(key);"
        print "}"
        print ""
        return
    } else if(name == "IsKeyDown") {
        print "    if(!g_kryon_keyboard_input_enabled)"
        print "        return false;"
        print "    if(g_kryon_key_down_callback != NULL && k_key_prefers_platform(key))"
        print "        return g_kryon_key_down_callback(key);"
        print "    if(" prefix name "(" backend_args "))"
        print "        return true;"
        print "    return g_kryon_key_down_callback != NULL &&"
        print "           g_kryon_key_down_callback(key);"
        print "}"
        print ""
        return
    } else if(name == "IsMouseButtonPressed" || name == "IsMouseButtonDown" || name == "IsMouseButtonReleased") {
        print "    if(g_kryon_input_override.enabled &&"
        print "       (!g_kryon_input_override.mouse_inside ||"
        print "        !g_kryon_input_override.pass_buttons))"
        print "        return false;"
    } else if(name == "IsMouseButtonUp") {
        print "    if(g_kryon_input_override.enabled &&"
        print "       (!g_kryon_input_override.mouse_inside ||"
        print "        !g_kryon_input_override.pass_buttons))"
        print "        return true;"
    } else if(name == "GetMouseX") {
        print "    if(g_kryon_input_override.enabled)"
        print "        return (int)g_kryon_input_override.mouse_position.x;"
    } else if(name == "GetMouseY") {
        print "    if(g_kryon_input_override.enabled)"
        print "        return (int)g_kryon_input_override.mouse_position.y;"
    } else if(name == "GetMousePosition") {
        print "    if(g_kryon_input_override.enabled)"
        print "        return g_kryon_input_override.mouse_position;"
    } else if(name == "GetMouseDelta") {
        print "    if(g_kryon_input_override.enabled)"
        print "        return g_kryon_input_override.mouse_delta;"
    } else if(name == "GetMouseWheelMove") {
        print "    if(g_kryon_input_override.enabled &&"
        print "       (!g_kryon_input_override.mouse_inside ||"
        print "        !g_kryon_input_override.pass_buttons))"
        print "        return 0.0f;"
    } else if(name == "GetMouseWheelMoveV") {
        print "    if(g_kryon_input_override.enabled &&"
        print "       (!g_kryon_input_override.mouse_inside ||"
        print "        !g_kryon_input_override.pass_buttons))"
        print "        return (Vector2){0.0f, 0.0f};"
    }
    if(returns_void) {
        print "    " prefix name "(" backend_args ");"
    } else {
        print "    return " prefix name "(" backend_args ");"
    }
    print "}"
    print ""
}

function emit_variadic_wrapper(return_type, name, args, fixed_args, backend_args) {
    print "extern " return_type " " prefix name "(" args ");"
    print return_type " " name "(" args ")"
    print "{"
    if(name == "TextFormat")
        print "    static char text_buffer[4096];"
    else
        print "    char text_buffer[4096];"
    print "    va_list ap;"
    print "    va_start(ap, text);"
    print "    vsnprintf(text_buffer, sizeof(text_buffer), text, ap);"
    print "    va_end(ap);"
    if(name == "TraceLog") {
        print "    " prefix name "(logLevel, \"%s\", text_buffer);"
    } else {
        print "    (void)" prefix name ";"
        print "    return text_buffer;"
    }
    print "}"
    print ""
}

BEGIN {
    print "/* Generated by tools/generate-kryon-compat.sh; do not edit. */"
    print "#include \"kryon.h\""
    print "#include <stdarg.h>"
    print "#include <stdio.h>"
    print ""
    print "#define KRYON_INPUT_OVERRIDE_STACK_CAP 8"
    print "static KryonInputOverride g_kryon_input_override = {0};"
    print "static KryonInputOverride g_kryon_input_override_stack[KRYON_INPUT_OVERRIDE_STACK_CAP];"
    print "static int g_kryon_input_override_depth = 0;"
    print "static int g_kryon_keyboard_input_enabled = 1;"
    print "static KeyInputPlatformCallback g_kryon_key_input_update_callback = NULL;"
    print "static KeyPlatformCallback g_kryon_key_pressed_callback = NULL;"
    print "static KeyPlatformCallback g_kryon_key_down_callback = NULL;"
    print ""
    print "static int k_key_prefers_platform(int key)"
    print "{"
    print "    return key >= 32 && key <= 126;"
    print "}"
    print ""
    print "void BeginKryonInputOverride(KryonInputOverride input)"
    print "{"
    print "    if(g_kryon_input_override_depth < KRYON_INPUT_OVERRIDE_STACK_CAP)"
    print "        g_kryon_input_override_stack[g_kryon_input_override_depth++] ="
    print "            g_kryon_input_override;"
    print "    input.enabled = 1;"
    print "    g_kryon_input_override = input;"
    print "}"
    print ""
    print "void EndKryonInputOverride(void)"
    print "{"
    print "    if(g_kryon_input_override_depth > 0) {"
    print "        g_kryon_input_override ="
    print "            g_kryon_input_override_stack[--g_kryon_input_override_depth];"
    print "        return;"
    print "    }"
    print "    g_kryon_input_override = (KryonInputOverride){0};"
    print "}"
    print ""
    print "int SetKeyboardInputEnabled(int enabled)"
    print "{"
    print "    int old = g_kryon_keyboard_input_enabled;"
    print ""
    print "    g_kryon_keyboard_input_enabled = enabled != 0;"
    print "    return old;"
    print "}"
    print ""
    print "int KeyboardInputEnabled(void)"
    print "{"
    print "    return g_kryon_keyboard_input_enabled;"
    print "}"
    print ""
    print "void SetKeyPlatformCallbacks(KeyInputPlatformCallback update,"
    print "                             KeyPlatformCallback key_pressed,"
    print "                             KeyPlatformCallback key_down)"
    print "{"
    print "    g_kryon_key_input_update_callback = update;"
    print "    g_kryon_key_pressed_callback = key_pressed;"
    print "    g_kryon_key_down_callback = key_down;"
    print "}"
    print ""
    print "void UpdateKeyPlatformState(void)"
    print "{"
    print "    if(g_kryon_key_input_update_callback != NULL)"
    print "        g_kryon_key_input_update_callback();"
    print "}"
    print ""
}

/^[[:space:]]*(RLAPI|RMAPI)[[:space:]]/ {
    line = $0
    sub(/\/\/.*$/, "", line)
    line = trim(line)
    sub(/;$/, "", line)
    prefix_text = line
    sub(/\(.*/, "", prefix_text)
    name = function_name_from_prefix(prefix_text)
    return_type = return_type_from_prefix(prefix_text, name)
    args = line
    sub(/^[^(]*\(/, "", args)
    sub(/\)$/, "", args)
    if(args ~ /\.\.\./) {
        emit_variadic_wrapper(return_type, name, args)
    } else {
        emit_regular_wrapper(return_type, name, args, call_args(args), return_type == "void")
    }
}
' "$raylib_header" > "$wrapper_source"

# Null backend: a link-time backend (KRYON_BACKEND=null) that provides a
# zero-return no-op stub for every public-surface symbol so libkryon.a links
# and runs headless with no GPU/window. Generated from the same raylib.h so it
# stays in sync with the surface automatically. Used for widget unit tests.
awk -v prefix="$backend_prefix" '
function trim(s) {
    sub(/^[[:space:]]+/, "", s)
    sub(/[[:space:]]+$/, "", s)
    return s
}

function function_name_from_prefix(prefix_text, parts, n) {
    n = split(prefix_text, parts, /[[:space:]\*]+/)
    return parts[n]
}

function return_type_from_prefix(prefix_text, name) {
    sub(/^[[:space:]]*(RLAPI|RMAPI)[[:space:]]+/, "", prefix_text)
    sub("[[:space:]]*" name "$", "", prefix_text)
    return trim(prefix_text)
}

function is_pointer_return(return_type) {
    return return_type ~ /\*$/
}

function arg_name(arg, parts, n, name) {
    arg = trim(arg)
    sub(/=.*/, "", arg)
    gsub(/\[[^]]*\]/, "", arg)
    n = split(arg, parts, /[[:space:]\*]+/)
    name = parts[n]
    gsub(/[^A-Za-z0-9_]/, "", name)
    return name
}

BEGIN {
    print "/* Generated by tools/generate-kryon-compat.sh; do not edit. */"
    print "/* Null backend: zero-return no-op stubs for the kryon surface."
    print " * Selected via KRYON_BACKEND=null for headless links (tests). */"
    print "#include \"kryon.h\""
    print "#include <stdarg.h>"
    print "#include <stdio.h>"
    print ""
}

/^[[:space:]]*(RLAPI|RMAPI)[[:space:]]/ {
    line = $0
    sub(/\/\/.*$/, "", line)
    line = trim(line)
    sub(/;$/, "", line)
    prefix_text = line
    sub(/\(.*/, "", prefix_text)
    name = function_name_from_prefix(prefix_text)
    return_type = return_type_from_prefix(prefix_text, name)
    args = line
    sub(/^[^(]*\(/, "", args)
    sub(/\)$/, "", args)

    # Variadic stubs: TextFormat returns "", TraceLog is a no-op.
    if(name == "TextFormat") {
        print "const char *TextFormat(const char *text, ...) { (void)text; return \"\"; }"
        print ""
        next
    }
    if(name == "TraceLog") {
        print "void TraceLog(int logLevel, const char *text, ...) { (void)logLevel; (void)text; }"
        print ""
        next
    }

    print return_type " " name "(" args ")"
    print "{"
    # Cast every named parameter to void to suppress -Wunused-parameter.
    n_args = split(args, arg_parts, /,[[:space:]]*/)
    for(ai = 1; ai <= n_args; ai++) {
        an = arg_name(arg_parts[ai])
        if(an != "" && an != "void")
            print "    (void)" an ";"
    }
    if(return_type == "void") {
        # nothing
    } else if(is_pointer_return(return_type)) {
        print "    return 0;"
    } else if(return_type ~ /^(int|long|short|char|bool|unsigned|float|double|size_t|[us]int8_t|[us]int16_t|[us]int32_t|[us]int64_t|GLenum|GLuint|GLint|GLfloat)/ ||
             return_type ~ /(_t|Flags|Key|MouseButton|Cursor|Gesture|BlendMode|TextureFilter|CubemapLayout|ShaderLocationIndex|ShaderUniformDataType|ShaderAttributeDataType|PixelFormat|BlendMode|Tex2D|MaterialMapIndex|NPatchLayout|KeyboardKey|GamepadButton|GamepadAxis)$/ ) {
        print "    return 0;"
    } else {
        # struct return (Color, Rectangle, Vector2, Image, Texture2D, Font, ...) -> zero-init
        print "    " return_type " r = {0};"
        print "    return r;"
    }
    print "}"
    print ""
}
' "$raylib_header" > "$null_backend_source"
