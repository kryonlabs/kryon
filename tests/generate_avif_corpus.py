#!/usr/bin/env python3
"""Build the AVIF engine corpus and its strict per-target digests.

The tiny lossless cases come from generate_avif_fixtures.py. This adds the
decoder classes Kryon apps ship: small 4:4:4 UI art with alpha, a 4:4:4 photo,
a 12 MP 4:2:0 photo and real Jungle q35 assets. --encode re-creates the Pillow
encodes (encoder versions change bytes, so committed .avif files are
canonical). The digest module always derives from the libaom oracle and must
equal the avif package's independent strict goldens where they exist.
"""
import argparse
import hashlib
from pathlib import Path
import shutil
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parent.parent
FIXTURES = ROOT/'tests/fixtures/avif'
SMALL = ('rgba8', 'rgba10', 'rgba12', 'gray8', 'gray10', 'gray12',
         'transform00', 'transform01', 'transform10', 'transform11', 'transform20', 'transform21',
         'transform30', 'transform31', 'premultiplied', 'opaque', 'animated')
CORPUS = ('ui-icon-444', 'photo-444', 'photo-420-large', 'jungle-clownfish', 'jungle-title')


def fnv1a64(data):
    value = 0xcbf29ce484222325
    for byte in data:
        value = ((value ^ byte) * 0x100000001b3) & 0xffffffffffffffff
    return value


def encode(libavif, jungle):
    from PIL import Image, ImageDraw
    icon = Image.new('RGBA', (48, 48), (0, 0, 0, 0))
    draw = ImageDraw.Draw(icon)
    draw.rounded_rectangle((4, 4, 43, 43), radius=10, fill=(46, 125, 50, 255))
    draw.ellipse((14, 12, 33, 31), fill=(255, 255, 255, 230))
    draw.polygon([(24, 22), (16, 38), (32, 38)], fill=(255, 213, 79, 200))
    icon.save(FIXTURES/'ui-icon-444.avif', 'AVIF', quality=90, subsampling='4:4:4', speed=6)
    # Strip ICC/EXIF: strict decoding rejects colour it cannot honour.
    photo = Image.open(libavif/'tests/data/dog_exif_extended_xmp_icc.jpg').convert('RGB')
    photo = Image.frombytes('RGB', photo.size, photo.tobytes())
    photo.save(FIXTURES/'photo-420-large.avif', 'AVIF', quality=35, subsampling='4:2:0', speed=6)
    photo.resize((768, 576), Image.LANCZOS).save(FIXTURES/'photo-444.avif', 'AVIF', quality=60, subsampling='4:4:4', speed=6)
    shutil.copyfile(jungle, FIXTURES/'jungle-clownfish.avif')
    # PNG control for the browser's unsupported-AVIF run.
    Image.frombytes('RGBA', (8, 6), (FIXTURES/'rgba8.rgba').read_bytes()).save(FIXTURES/'control.png', optimize=True)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--avif-cli', type=Path, required=True, help='avif package tools/avif.zi binary')
    parser.add_argument('--avif-package', type=Path, required=True)
    parser.add_argument('--encode', action='store_true')
    parser.add_argument('--libavif', type=Path)
    parser.add_argument('--jungle', type=Path, help='Jungle q35 asset, e.g. assets/fishing/clownfish.avif')
    args = parser.parse_args()
    if args.encode:
        if not args.libavif or not args.jungle:
            parser.error('--encode needs --libavif and --jungle')
        encode(args.libavif, args.jungle)
    rows = []
    with tempfile.TemporaryDirectory() as temporary:
        for name in SMALL + CORPUS:
            output = Path(temporary)/(name + '.rgba')
            report = subprocess.run([args.avif_cli, FIXTURES/(name + '.avif'), output, 'libaom'],
                                    check=True, text=True, stdout=subprocess.PIPE).stdout
            width, height = map(int, report.split()[0].split('x'))
            pixels = output.read_bytes()
            strict = args.avif_package/'tests/fixtures'/(name + '.strict.rgba')
            if strict.exists() and strict.read_bytes() != pixels:
                raise SystemExit(f'{name}: libaom oracle differs from the package strict golden')
            rows.append((name, width, height, fnv1a64(pixels), hashlib.sha256((FIXTURES/(name + '.avif')).read_bytes()).hexdigest()))
    lines = ['// Generated by tests/generate_avif_corpus.py from the libaom oracle; do not edit.',
             '// Every engine, thread count and target must reproduce these RGBA8 digests.',
             'AvifStrictCase :: struct { name: string; width: s32; height: s32; digest: u64; }',
             f'AVIF_STRICT_COUNT :: {len(rows)}',
             'AvifStrictCaseAt :: (index: s64) -> AvifStrictCase {',
             f'    cases: [{len(rows)}]AvifStrictCase = .[']
    lines += [f'        AvifStrictCase.{{"{name}", {width}, {height}, 0x{digest:016x}}}{"," if i + 1 < len(rows) else ""}'
              for i, (name, width, height, digest, _) in enumerate(rows)]
    lines += ['    ]', '    return cases[index]', '}', '']
    (ROOT/'tests/avif_strict_digests.zi').write_text('\n'.join(lines))
    for name, width, height, digest, sha in rows:
        if name in CORPUS:
            print(f'{name}.avif {width}x{height} {(FIXTURES/(name + ".avif")).stat().st_size} bytes sha256 {sha}')


if __name__ == '__main__':
    main()
