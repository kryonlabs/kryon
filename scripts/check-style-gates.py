#!/usr/bin/env python3
"""Style separation scanners from plan/style/07-testing-and-gates.md.

Usage: check-style-gates.py <gate>

Gates: style-facts-bridge-check paint-style-leak-check no-theme-chrome-check
       no-glow-pack-check visual-props-check

Every gate is a ratchet: allowlists record today's classified sites so new
violations fail immediately while the migration keeps shrinking the counts.
"""
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def ls_files(*patterns):
    out = subprocess.run(["git", "-C", str(ROOT), "ls-files", *patterns],
                         capture_output=True, text=True, check=True).stdout
    return [ROOT / line for line in out.splitlines()]


def text_lines(path):
    try:
        return path.read_text(errors="replace").splitlines()
    except OSError:
        return []


def is_generated(path):
    return "Code generated by" in "\n".join(text_lines(path)[:3])


def violations(name, hits):
    if not hits:
        print(f"{name}: ok")
        return
    for hit in hits[:20]:
        print(f"{name}: {hit}")
    print(f"{name}: {len(hits)} violation(s) - see plan/style/07-testing-and-gates.md")
    sys.exit(1)


def style_facts_bridge_check():
    pat = re.compile(r"\bStyleControl(Role)?Facts\s*\(")
    hits = []
    for path in ls_files("src/ui/*.c", "src/ui/*.h"):
        if path.name.startswith("style_sheet"):
            continue
        for i, line in enumerate(text_lines(path), 1):
            if pat.search(line):
                hits.append(f"{path.relative_to(ROOT)}:{i} constructs style facts directly")
    for path in ls_files("go/kryon/*.go"):
        if is_generated(path) or path.name.endswith("_test.go"):
            continue
        if path.name == "style_sheet.go":
            continue
        for i, line in enumerate(text_lines(path), 1):
            if pat.search(line):
                hits.append(f"{path.relative_to(ROOT)}:{i} constructs style facts directly")
    violations("style-facts-bridge-check", hits)


CHROME_GETTERS = re.compile(
    r"\bGetTheme(Button|ButtonHover|Surface|Background|Text|Border|Selection|Circle|Icon|Link)\s*\(")
GETTER_ALLOWLIST = {
    # Legacy theme catalog application (ApplyCurrentTheme). Kept until
    # downstream apps migrate off the pre-KSS
    # theme API; removal is tracked by plan/style/09-legacy-removal.md.
    # Classified: legacy bridge, not new-code product chrome.
    "src/ui/ui.c": 5,
}


def paint_style_leak_check():
    hits = []
    for path in ls_files("src/ui/*.c"):
        rel = str(path.relative_to(ROOT))
        count = sum(1 for line in text_lines(path) if CHROME_GETTERS.search(line))
        limit = GETTER_ALLOWLIST.get(rel, 0)
        if count > limit:
            hits.append(f"{rel}: {count} theme chrome getter calls (allowlist {limit})")
    violations("paint-style-leak-check", hits)


BASE_ALLOWLIST = {}
GO_BASE_ALLOWLIST = {
    # Caller-supplied font size/opacity and gap/padding metrics used as style
    # bases. Classified: content metrics per the documented metrics contract,
    # not product decoration; shrink only if the props move into KSS.
    "go/kryon/control_style_host.go": 4,
}


def no_theme_chrome_check():
    base_pat = re.compile(r"StyleData base = \{(?!0\})|ResolveActiveStyle\(\s*\(StyleData\)\{\s*\.fields")
    go_base_pat = re.compile(r"StyleData\{Fields:|packStyle\(Style\{Fields:")
    hits = []
    for path in ls_files("src/ui/*.c"):
        rel = str(path.relative_to(ROOT))
        count = sum(1 for line in text_lines(path) if base_pat.search(line))
        limit = BASE_ALLOWLIST.get(rel, 0)
        if count > limit:
            hits.append(f"{rel}: {count} nonzero visual style bases (allowlist {limit})")
    for path in ls_files("go/kryon/*.go"):
        if is_generated(path) or path.name.endswith("_test.go"):
            continue
        rel = str(path.relative_to(ROOT))
        count = sum(1 for line in text_lines(path) if go_base_pat.search(line))
        limit = GO_BASE_ALLOWLIST.get(rel, 0)
        if count > limit:
            hits.append(f"{rel}: {count} inline style bases (allowlist {limit})")
    violations("no-theme-chrome-check", hits)


GLOW = re.compile(r"<glow>|@pack glow|styles/kryon/glow")


def no_glow_pack_check():
    hits = []
    for path in ls_files("src", "runtime/*.kry", "go/kryon/*.go",
                         "styles", "examples", "include"):
        for i, line in enumerate(text_lines(path), 1):
            if GLOW.search(line):
                hits.append(f"{path.relative_to(ROOT)}:{i} references the deleted glow pack")
    violations("no-glow-pack-check", hits)


VISUAL_PROP = re.compile(r"^\s*(background|foreground|border|radius|opacity|color)[a-z_]*:", re.I)
VISUAL_PROP_RATCHET = 10  # legacy visual props deleted in Phase 10


def visual_props_check():
    hits, count = [], 0
    for path in ls_files("runtime/*_props.kry"):
        for i, line in enumerate(text_lines(path), 1):
            if VISUAL_PROP.search(line):
                count += 1
                hits.append(f"{path.relative_to(ROOT)}:{i} visual prop field")
    if count > VISUAL_PROP_RATCHET:
        violations("visual-props-check", hits)
    print(f"visual-props-check: ok ({count}/{VISUAL_PROP_RATCHET} legacy visual props)")


GATES = {
    "style-facts-bridge-check": style_facts_bridge_check,
    "paint-style-leak-check": paint_style_leak_check,
    "no-theme-chrome-check": no_theme_chrome_check,
    "no-glow-pack-check": no_glow_pack_check,
    "visual-props-check": visual_props_check,
}


def main():
    if len(sys.argv) != 2 or sys.argv[1] not in GATES:
        print(__doc__)
        sys.exit(2)
    GATES[sys.argv[1]]()


if __name__ == "__main__":
    main()
